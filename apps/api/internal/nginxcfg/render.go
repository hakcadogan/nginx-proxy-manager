// TLSPaths maps certificate id -> filesystem paths for nginx.
type TLSPaths struct {
	CertPath string
	KeyPath  string
	// OCSP enables ssl_stapling when the chain includes an issuer (e.g. ACME fullchain).
	// Self-signed / leaf-only PEMs must stay false — nginx warns and ignores stapling otherwise (REQ-SSL-014).
	OCSP bool
}

// RenderInput is the declarative desired state for nginx (REQ-CFG-001, REQ-SSL-011/012, REQ-LB-*, REQ-WAF-*).
type RenderInput struct {
	Hosts          []models.ProxyHost
	Profiles       map[string]models.RateLimitProfile
	Certs          map[string]TLSPaths
	Upstreams      map[string]models.Upstream // id string -> pool
	WAF            *WAFRenderInput
	IPPolicies     []models.IPPolicy
	ACMEWebRoot    string
	TrustedProxies string // CSV of IP/CIDR
	RealIPHeader   string
	// CustomConfDir overrides /data/nginx/custom (tests); empty → CustomConfDir const.
	CustomConfDir string
	// IDSEnforcement: "active" (default) applies allow/deny; "passive" skips nginx deny/allow (REQ-IDS-019).
	IDSEnforcement string
}

var (
	domainRe   = regexp.MustCompile(`(?i)^(\*\.)?([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$|^localhost$|^(\d{1,3}\.){3}\d{1,3}$`)
	hostRe     = regexp.MustCompile(`(?i)^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)*[a-z0-9-]{1,63}$|^(\d{1,3}\.){3}\d{1,3}$|^\[?[0-9a-f:]+\]?$`)
	pathRe     = regexp.MustCompile(`^/[A-Za-z0-9._~!$&'()*+,;=:@%/-]*$`)
	headerRe   = regexp.MustCompile(`(?i)^[A-Za-z0-9-]+$`)
	timeoutRe  = regexp.MustCompile(`^[0-9]+(ms|s|m)$`)
	hashKeyRe  = regexp.MustCompile(`^\$[A-Za-z0-9_]+$`)
	algoValid  = map[string]bool{
		"round_robin": true, "weighted_round_robin": true, "least_conn": true,
		"ip_hash": true, "hash": true, "hash_consistent": true,
	}
)

