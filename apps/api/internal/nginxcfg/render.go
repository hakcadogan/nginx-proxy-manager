// NormalizeHostFields fills listen/body/timeout defaults for render and validation.
func NormalizeHostFields(h *models.ProxyHost) {
	if !h.ListenHTTP && !h.ListenHTTPS {
		h.ListenHTTP = true
		h.ListenHTTPS = true
		h.HTTP2 = true
	}
	if h.ClientMaxBodySize == "" {
		h.ClientMaxBodySize = "10m"
	}
	if h.ConnectTimeout == "" {
		h.ConnectTimeout = "5s"
	}
	if h.SendTimeout == "" {
		h.SendTimeout = "60s"
	}
	if h.ReadTimeout == "" {
		h.ReadTimeout = "60s"
	}
	if h.ProxyProtocol == "" {
		h.ProxyProtocol = "http"
	}
	if strings.TrimSpace(h.AccessLogFormat) == "" {
		h.AccessLogFormat = "main"
	} else {
		h.AccessLogFormat = strings.ToLower(strings.TrimSpace(h.AccessLogFormat))
	}
}

// SecurityHeadersBlock renders HSTS / security header presets (REQ-PROXY-013).
func SecurityHeadersBlock(preset string) string {
	switch strings.ToLower(strings.TrimSpace(preset)) {
	case "basic":
		return `        add_header X-Content-Type-Options nosniff always;
        add_header X-Frame-Options SAMEORIGIN always;
        add_header Referrer-Policy strict-origin-when-cross-origin always;
`
	case "strict":
		return `        add_header X-Content-Type-Options nosniff always;
        add_header X-Frame-Options DENY always;
        add_header Referrer-Policy no-referrer always;
        add_header Strict-Transport-Security "max-age=63072000; includeSubDomains" always;
        add_header Content-Security-Policy "default-src 'self'" always;
`
	default:
		return ""
	}
}

func ValidateHost(h models.ProxyHost) error {
	if err := ValidateAccessLogFormat(h.AccessLogFormat); err != nil {
		return err
	}
	NormalizeHostFields(&h)
	switch h.SecurityHeadersPreset {
	case "", "none", "basic", "strict":
	default:
		return fmt.Errorf("invalid security_headers_preset")
	}
	if h.ProxyProtocol != "http" && h.ProxyProtocol != "grpc" {
		return fmt.Errorf("invalid proxy_protocol")
	}
	if !h.ListenHTTP && !h.ListenHTTPS {
		return fmt.Errorf("at least one of listen_http or listen_https required")
	}
	if err := ValidateSize(h.ClientMaxBodySize); err != nil {
		return fmt.Errorf("client_max_body_size: %w", err)
	}
	for _, t := range []string{h.ConnectTimeout, h.SendTimeout, h.ReadTimeout} {
		if t != "" && !timeoutRe.MatchString(t) {
			return fmt.Errorf("invalid timeout %q", t)
		}
	}
	if !domainRe.MatchString(h.PrimaryDomain) {
		return fmt.Errorf("invalid primary_domain")
	}
	for _, a := range h.Aliases {
		if !domainRe.MatchString(a) {
			return fmt.Errorf("invalid alias %q", a)
		}
	}
	if h.UpstreamID == nil {
		if h.UpstreamScheme != "http" && h.UpstreamScheme != "https" {
			return fmt.Errorf("invalid upstream_scheme")
		}
		if !hostRe.MatchString(h.UpstreamHost) {
			return fmt.Errorf("invalid upstream_host")
		}
		if isBlockedUpstream(h.UpstreamHost) {
			return fmt.Errorf("upstream_host is not allowed")
		}
		if h.UpstreamPort < 1 || h.UpstreamPort > 65535 {
			return fmt.Errorf("invalid upstream_port")
		}
	} else if h.UpstreamScheme != "" && h.UpstreamScheme != "http" && h.UpstreamScheme != "https" {
		return fmt.Errorf("invalid upstream_scheme")
	}
	if !pathRe.MatchString(h.PathPrefix) {
		return fmt.Errorf("invalid path_prefix")
	}
	for _, hdr := range h.CustomHeaders {
		if hdr.Action != "add" && hdr.Action != "remove" {
			return fmt.Errorf("invalid header action")
		}
		if !headerRe.MatchString(hdr.Name) {
			return fmt.Errorf("invalid header name")
		}
		if strings.ContainsAny(hdr.Value, "\r\n") {
			return fmt.Errorf("header value contains newline")
		}
	}
	if _, err := NormalizeMethods(h.AllowedMethods); err != nil {
		return err
	}
	for _, loc := range h.Locations {
		if !pathRe.MatchString(loc.Path) {
			return fmt.Errorf("invalid location path")
		}
		if loc.UpstreamScheme != "http" && loc.UpstreamScheme != "https" {
			return fmt.Errorf("invalid location upstream_scheme")
		}
		if !hostRe.MatchString(loc.UpstreamHost) || isBlockedUpstream(loc.UpstreamHost) {
			return fmt.Errorf("invalid location upstream_host")
		}
		if _, err := NormalizeMethods(loc.AllowedMethods); err != nil {
			return fmt.Errorf("location %s: %w", loc.Path, err)
		}
		if loc.RateLimitProfileID != "" {
			if _, err := uuid.Parse(loc.RateLimitProfileID); err != nil {
				return fmt.Errorf("location %s: invalid rate_limit_profile_id", loc.Path)
			}
		}
	}
	return nil
}

func ValidateUpstream(u models.Upstream) error {
	if strings.TrimSpace(u.Name) == "" {
		return fmt.Errorf("name required")
	}
	if !algoValid[u.Algorithm] {
		return fmt.Errorf("invalid algorithm")
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return fmt.Errorf("invalid scheme")
	}
	if (u.Algorithm == "hash" || u.Algorithm == "hash_consistent") && !hashKeyRe.MatchString(u.HashKey) {
		return fmt.Errorf("invalid hash_key")
	}
	for _, t := range []string{u.ConnectTimeout, u.SendTimeout, u.ReadTimeout, u.FailTimeout} {
		if t != "" && !timeoutRe.MatchString(t) {
			return fmt.Errorf("invalid timeout %q", t)
		}
	}
	if u.MaxFails < 0 {
		return fmt.Errorf("invalid max_fails")
	}
	if u.HealthCheckIntervalSec != 0 && u.HealthCheckIntervalSec < 5 {
		return fmt.Errorf("health_check_interval_sec must be >= 5")
	}
	if u.HealthCheckPath != "" && !pathRe.MatchString(u.HealthCheckPath) {
		return fmt.Errorf("invalid health_check_path")
	}
	if u.SNI != "" && !hostRe.MatchString(u.SNI) {
		return fmt.Errorf("invalid sni")
	}
	if err := ValidateNextUpstream(u.NextUpstream); err != nil {
		return err
	}
	if u.NextUpstreamTries < 0 || u.NextUpstreamTries > 100 {
		return fmt.Errorf("invalid next_upstream_tries")
	}
	to := strings.TrimSpace(u.NextUpstreamTimeout)
	if to != "" && to != "0" && !timeoutRe.MatchString(to) {
		return fmt.Errorf("invalid next_upstream_timeout")
	}
	return nil
}

func ValidateMember(m models.UpstreamMember) error {
	if !hostRe.MatchString(m.Host) {
		return fmt.Errorf("invalid host")
	}
	if isBlockedUpstream(m.Host) {
		return fmt.Errorf("host is not allowed")
	}
	if m.Port < 1 || m.Port > 65535 {
		return fmt.Errorf("invalid port")
	}
	if m.Weight < 1 || m.Weight > 1000 {
		return fmt.Errorf("invalid weight")
	}
	if m.MaxConns < 0 || m.MaxConns > 100000 {
		return fmt.Errorf("invalid max_conns")
	}
	return nil
}

func isBlockedUpstream(host string) bool {
	h := strings.ToLower(strings.Trim(host, "[]"))
	blocked := []string{
		"localhost", "127.0.0.1", "0.0.0.0", "::1",
		"169.254.169.254", "metadata.google.internal",
	}
	for _, b := range blocked {
		if h == b {
			return true
		}
	}
	return false
}

func escapeNginxString(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", "", "\r", "", ";", "")
	return r.Replace(s)
}

func poolUpstreamName(id uuid.UUID) string {
	return "pool_" + strings.ReplaceAll(id.String(), "-", "")
}

// RenderPoolUpstream builds an upstream {} block (REQ-LB-002..011).
func RenderPoolUpstream(u models.Upstream) (string, error) {
	if err := ValidateUpstream(u); err != nil {
		return "", err
	}
	if len(u.Members) == 0 {
		return "", fmt.Errorf("upstream %q has no members", u.Name)
	}
	var b strings.Builder
	name := poolUpstreamName(u.ID)
	b.WriteString(fmt.Sprintf("    upstream %s {\n", name))
	switch u.Algorithm {
	case "least_conn":
		b.WriteString("        least_conn;\n")
	case "ip_hash":
		b.WriteString("        ip_hash;\n")
	case "hash":
		b.WriteString(fmt.Sprintf("        hash %s;\n", escapeNginxString(u.HashKey)))
	case "hash_consistent":
		b.WriteString(fmt.Sprintf("        hash %s consistent;\n", escapeNginxString(u.HashKey)))
	}
	for _, m := range u.Members {
		if err := ValidateMember(m); err != nil {
			return "", fmt.Errorf("member %s:%d: %w", m.Host, m.Port, err)
		}
		line := fmt.Sprintf("        server %s:%d", escapeNginxString(m.Host), m.Port)
		// ip_hash does not support weight/backup in older nginx; weight is ignored with ip_hash.
		if u.Algorithm != "ip_hash" && m.Weight > 1 {
			line += fmt.Sprintf(" weight=%d", m.Weight)
		}
		if m.MaxConns > 0 {
			line += fmt.Sprintf(" max_conns=%d", m.MaxConns)
		}
		line += fmt.Sprintf(" max_fails=%d fail_timeout=%s", u.MaxFails, escapeNginxString(u.FailTimeout))
		if m.IsBackup && u.Algorithm != "ip_hash" {
			line += " backup"
		}
		if m.IsDown || m.IsDrain {
			line += " down"
		}
		line += ";\n"
		b.WriteString(line)
	}
	b.WriteString("    }")
	return b.String(), nil
}

func Render(in RenderInput) (string, string, error) {
	b, err := RenderAll(in)
	if err != nil {
		return "", "", err
	}
	// Combined view for callers/tests that assert host directives in one string.
	return CombinedConf(b), b.Checksum, nil
}

// CombinedConf joins main + proxy_host files (deterministic order) for inspection.
func CombinedConf(b RenderBundle) string {
	var sb strings.Builder
	sb.WriteString(b.Main)
	names := make([]string, 0, len(b.ProxyHostFiles))
	for n := range b.ProxyHostFiles {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		sb.WriteString("\n# --- ")
		sb.WriteString(n)
		sb.WriteString(" ---\n")
		sb.WriteString(b.ProxyHostFiles[n])
	}
	return sb.String()
}

// RenderAll builds main conf + per-host proxy_host files (NPM-style layout).
func RenderAll(in RenderInput) (RenderBundle, error) {
	out := RenderBundle{ProxyHostFiles: map[string]string{}}
	if in.ACMEWebRoot == "" {
		in.ACMEWebRoot = "/var/lib/nsp/acme-www"
	}
	if in.Upstreams == nil {
		in.Upstreams = map[string]models.Upstream{}
	}
	var zones []limitZone
	var upstreamBlocks []string
	zoneSeen := map[string]bool{}
	poolSeen := map[string]bool{}

	ipAccess, err := RenderIPAccessMode(in.IPPolicies, in.IDSEnforcement)
	if err != nil {
		return out, err
	}

	tmpl := template.New("server")
	tmpl, err = tmpl.Parse(serverTemplate)
	if err != nil {
		return out, err
	}
	if _, err := tmpl.New("proxy_locations").Parse(proxyLocationsTemplate); err != nil {
		return out, err
	}

	custom := LoadCustomIncludes(in.CustomConfDir)

	for i, h := range in.Hosts {
		NormalizeHostFields(&h)
		if err := ValidateHost(h); err != nil {
			return out, fmt.Errorf("host %s: %w", h.PrimaryDomain, err)
		}
		if !h.Enabled {
			continue
		}

		var upName, scheme, connectTO, sendTO, readTO, sni string
		var poolPtr *models.Upstream
		httpsUp := false
		connectTO, sendTO, readTO = h.ConnectTimeout, h.SendTimeout, h.ReadTimeout

		if h.UpstreamID != nil {
			u, ok := in.Upstreams[h.UpstreamID.String()]
			if !ok {
				return out, fmt.Errorf("host %s: upstream pool not found", h.PrimaryDomain)
			}
			poolPtr = &u
			upName = poolUpstreamName(u.ID)
			if !poolSeen[upName] {
				block, err := RenderPoolUpstream(u)
				if err != nil {
					return out, err
				}
				upstreamBlocks = append(upstreamBlocks, block)
				poolSeen[upName] = true
			}
			scheme = u.Scheme
			// Pool-bound hosts use pool timeouts (configured on LB page).
			if u.ConnectTimeout != "" {
				connectTO = u.ConnectTimeout
			}
			if u.SendTimeout != "" {
				sendTO = u.SendTimeout
			}
			if u.ReadTimeout != "" {
				readTO = u.ReadTimeout
			}
			httpsUp = u.Scheme == "https"
			sni = u.SNI
			if sni == "" && httpsUp {
				sni = h.PrimaryDomain
			}
		} else {
			upName = fmt.Sprintf("up_%d", i)
			upstreamBlocks = append(upstreamBlocks, fmt.Sprintf(
				"    upstream %s {\n        server %s:%d;\n    }",
				upName, escapeNginxString(h.UpstreamHost), h.UpstreamPort,
			))
			scheme = h.UpstreamScheme
			httpsUp = h.UpstreamScheme == "https"
		}

		nextUp, err := NextUpstreamFromPool(poolPtr)
		if err != nil {
			return out, fmt.Errorf("host %s: next_upstream: %w", h.PrimaryDomain, err)
		}

		proxyPass := fmt.Sprintf("%s://%s", scheme, upName)
		grpc := h.ProxyProtocol == "grpc"
		if grpc {
			if scheme == "https" {
				proxyPass = fmt.Sprintf("grpcs://%s", upName)
			} else {
				proxyPass = fmt.Sprintf("grpc://%s", upName)
			}
		}

		names := []string{escapeNginxString(h.PrimaryDomain)}
		for _, a := range h.Aliases {
			names = append(names, escapeNginxString(a))
		}

		logBase := sanitizeLogName(h.PrimaryDomain)
		logFmt := NginxFormatName(h.AccessLogFormat)
		sv := serverView{
			ServerNames:       strings.Join(names, " "),
			LogName:           logBase,
			AccessLog:         h.AccessLogEnabled,
			AccessLogPath:     escapeNginxString(ProxyHostLogDir + "/" + logBase + ".log"),
			SSLAccessLogPath:  escapeNginxString(ProxyHostLogDir + "/" + logBase + ".ssl.log"),
			AccessLogFormat:   logFmt,
			ErrorLog:          h.ErrorLogEnabled,
			ErrorLogPath:      escapeNginxString(ProxyHostErrLogDir + "/" + logBase + ".log"),
			SSLErrorLogPath:   escapeNginxString(ProxyHostErrLogDir + "/" + logBase + ".ssl.log"),
			ErrorLogLevel:     "warn",
			CustomServerProxy: custom.ServerProxy,
			ForceHTTPS:        h.ForceHTTPS,
			ListenHTTP:        h.ListenHTTP,
			ListenHTTPS:       h.ListenHTTPS,
			HTTP2:             h.HTTP2,
			ClientMaxBodySize: escapeNginxString(h.ClientMaxBodySize),
			ACMEWebRoot:       escapeNginxString(in.ACMEWebRoot),
			PathPrefix:        escapeNginxString(h.PathPrefix),
			ProxyPass:         proxyPass,
			Websocket:         h.WebsocketSupport && !grpc,
			GRPC:              grpc,
			ConnectTimeout:    escapeNginxString(connectTO),
			SendTimeout:       escapeNginxString(sendTO),
			ReadTimeout:       escapeNginxString(readTO),
			NextUpstream:      nextUp,
			HTTPSUpstream:     httpsUp && !grpc,
			SNI:               escapeNginxString(sni),
			MethodGuard:       RenderMethodGuard(h.AllowedMethods, "        "),
			SecurityHeaders:   SecurityHeadersBlock(h.SecurityHeadersPreset),
		}
		if in.WAF != nil {
			var hostPol *models.WAFPolicy
			if hp, ok := in.WAF.HostPolicy[h.ID.String()]; ok {
				hostPol = &hp
			}
			sv.WAFDirectives = HostEngineDirective(h.WAFEnabled, in.WAF.Global, hostPol)
		}
		if h.CertificateID != nil {
			if tp, ok := in.Certs[h.CertificateID.String()]; ok && tp.CertPath != "" && tp.KeyPath != "" {
				sv.HasTLS = true
				sv.CertPath = escapeNginxString(tp.CertPath)
				sv.KeyPath = escapeNginxString(tp.KeyPath)
				sv.OCSPStapling = tp.OCSP
			}
		}
		// IP-based rate/conn limits require trusted proxies so $remote_addr is the real client (REQ-RATE-008).
		ipRateOK := strings.TrimSpace(in.TrustedProxies) != ""
		ensureZone := func(p models.RateLimitProfile) (zname, cname string) {
			zname = "rl_" + sanitizeLogName(p.Name)
			cname = "cl_" + sanitizeLogName(p.Name)
			if !zoneSeen[zname] {
				zones = append(zones, limitZone{
					Name: zname, ConnName: cname, Rate: formatRate(p.RequestsPerSecond),
				})
				zoneSeen[zname] = true
			}
			return zname, cname
		}
		retryAfter := 0
		if ipRateOK && h.RateLimitProfileID != nil {
			if p, ok := in.Profiles[h.RateLimitProfileID.String()]; ok {
				zname, cname := ensureZone(p)
				sv.LimitReqZone = zname
				sv.LimitConnZone = cname
				sv.Burst = p.Burst
				sv.ConnLimit = p.ConnectionsPerIP
				retryAfter = NormalizeRetryAfterSeconds(p.RetryAfterSeconds, p.RequestsPerSecond)
			}
		}
		for _, hdr := range h.CustomHeaders {
			switch hdr.Action {
			case "add":
				sv.HeaderAdds = append(sv.HeaderAdds, headerAdd{Name: escapeNginxString(hdr.Name), Value: escapeNginxString(hdr.Value)})
			case "remove":
				sv.HeaderRemoves = append(sv.HeaderRemoves, escapeNginxString(hdr.Name))
			}
		}
		for _, loc := range h.Locations {
			locUp := fmt.Sprintf("up_%d_%s", i, sanitizeLogName(loc.Path))
			upstreamBlocks = append(upstreamBlocks, fmt.Sprintf(
				"    upstream %s {\n        server %s:%d;\n    }",
				locUp, escapeNginxString(loc.UpstreamHost), loc.UpstreamPort,
			))
			el := extraLoc{
				Path:        escapeNginxString(loc.Path),
				ProxyPass:   fmt.Sprintf("%s://%s", loc.UpstreamScheme, locUp),
				MethodGuard: RenderMethodGuard(loc.AllowedMethods, "            "),
			}
			if ipRateOK && loc.RateLimitProfileID != "" {
				if p, ok := in.Profiles[loc.RateLimitProfileID]; ok {
					zname, cname := ensureZone(p)
					el.LimitReqZone = zname
					el.LimitConnZone = cname
					el.Burst = p.Burst
					el.ConnLimit = p.ConnectionsPerIP
					ra := NormalizeRetryAfterSeconds(p.RetryAfterSeconds, p.RequestsPerSecond)
					if ra > retryAfter {
						retryAfter = ra
					}
				}
			}
			sv.ExtraLocations = append(sv.ExtraLocations, el)
		}
		sv.ErrorPages = ErrorPagesSnippetOpts("        ", retryAfter)

		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, sv); err != nil {
			return out, err
		}
		fname := proxyHostFileName(h)
		out.ProxyHostFiles[fname] = "# Generated by NSP — proxy host " + h.PrimaryDomain + "\n" + buf.String()
	}

	realIP, err := RenderRealIP(in.TrustedProxies, in.RealIPHeader)
	if err != nil {
		return out, err
	}

	mapTmpl, err := template.New("main").Parse(mainTemplate)
	if err != nil {
		return out, err
	}
	data := struct {
		LimitZones        []limitZone
		Upstreams         []string
		ACMEWebRoot       string
		RealIP            string
		IPAccess          string
		LogFormats        string
		ErrorLog          string
		FallbackAccessLog string
		FallbackErrorLog  string
		ProxyHostInclude  string
		CustomRootTop     string
		CustomRoot        string
		CustomHTTPTop     string
		CustomHTTP        string
		CustomEvents      string
		CustomStream      string
		CustomServerDead  string
		ErrorPages        string
	}{
		zones, upstreamBlocks, escapeNginxString(in.ACMEWebRoot), realIP, ipAccess,
		RenderLogFormatsBlock(),
		escapeNginxString(LogDir + "/error.log"),
		escapeNginxString(LogDir + "/fallback_access.log"),
		escapeNginxString(LogDir + "/fallback_error.log"),
		escapeNginxString(ProxyHostGlob),
		custom.RootTop, custom.Root, custom.HTTPTop, custom.HTTP, custom.Events,
		custom.StreamBlock, custom.ServerDead,
		ErrorPagesSnippet("        "),
	}

	var body bytes.Buffer
	if err := mapTmpl.Execute(&body, data); err != nil {
		return out, err
	}
	out.Main = injectWebsocketMap(body.String())
	out.Checksum = bundleChecksum(out)
	return out, nil
}

func proxyHostFileName(h models.ProxyHost) string {
	if h.ID != uuid.Nil {
		return h.ID.String() + ".conf"
	}
	return sanitizeLogName(h.PrimaryDomain) + ".conf"
}

func bundleChecksum(b RenderBundle) string {
	h := sha256.New()
	_, _ = h.Write([]byte(b.Main))
	names := make([]string, 0, len(b.ProxyHostFiles))
	for n := range b.ProxyHostFiles {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		_, _ = h.Write([]byte(n))
		_, _ = h.Write([]byte(b.ProxyHostFiles[n]))
	}
	return hex.EncodeToString(h.Sum(nil))
}

const (
	bundleMainMark = "\n###NSP_BUNDLE_MAIN###\n"
	bundleFileMark = "\n###NSP_BUNDLE_FILE:"
)

// EncodeBundle serializes main + proxy_host files for config_versions storage.
func EncodeBundle(b RenderBundle) string {
	var sb strings.Builder
	sb.WriteString(bundleMainMark)
	sb.WriteString(b.Main)
	names := make([]string, 0, len(b.ProxyHostFiles))
	for n := range b.ProxyHostFiles {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		sb.WriteString(bundleFileMark)
		sb.WriteString(n)
		sb.WriteString("###\n")
		sb.WriteString(b.ProxyHostFiles[n])
	}
	return sb.String()
}

// DecodeBundle restores a RenderBundle. Legacy monolithic conf → Main only.
func DecodeBundle(s string) RenderBundle {
	b := RenderBundle{ProxyHostFiles: map[string]string{}}
	if !strings.Contains(s, "###NSP_BUNDLE_MAIN###") {
		b.Main = s
		b.Checksum = bundleChecksum(b)
		return b
	}
	s = strings.TrimPrefix(s, "\n")
	rest := strings.TrimPrefix(s, "###NSP_BUNDLE_MAIN###\n")
	parts := strings.Split(rest, "\n###NSP_BUNDLE_FILE:")
	b.Main = parts[0]
	for _, p := range parts[1:] {
		idx := strings.Index(p, "###\n")
		if idx < 0 {
			continue
		}
		b.ProxyHostFiles[p[:idx]] = p[idx+4:]
	}
	b.Checksum = bundleChecksum(b)
	return b
}

func injectWebsocketMap(conf string) string {
	needle := "http {\n"
	idx := strings.Index(conf, needle)
	if idx < 0 {
		return conf
	}
	insert := `http {
    map $http_upgrade $connection_upgrade {
        default upgrade;
        ''      close;
    }
`
	return conf[:idx] + insert + conf[idx+len(needle):]
}

func sanitizeLogName(s string) string {
	s = strings.ToLower(s)
	var b strings.Builder
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	out := b.String()
	if out == "" {
		return "host"
	}
	return out
}

func formatRate(r float64) string {
	if r < 1 {
		return fmt.Sprintf("%.2f", r)
	}
	if r == float64(int(r)) {
		return fmt.Sprintf("%d", int(r))
	}
	return fmt.Sprintf("%.2f", r)
}
