var uaAllowPhraseRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9 ._\-/\(\);:+@]{0,127}$`)

// ValidateUAAllowlistPatterns rejects injection / oversized phrases (REQ-RATE-010).
func ValidateUAAllowlistPatterns(patterns []string) error {
	if len(patterns) > 200 {
		return fmt.Errorf("ua allowlist max 200 patterns")
	}
	seen := map[string]bool{}
	for _, p := range patterns {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		if strings.HasPrefix(p, "#") {
			return fmt.Errorf("comment lines not allowed in patterns")
		}
		if !uaAllowPhraseRe.MatchString(p) {
			return fmt.Errorf("invalid ua pattern %q", p)
		}
		key := strings.ToLower(p)
		if seen[key] {
			continue
		}
		seen[key] = true
	}
	return nil
}

// NormalizeUAAllowlist returns trimmed unique patterns in stable order.
func NormalizeUAAllowlist(patterns []string) []string {
	seen := map[string]bool{}
	out := make([]string, 0, len(patterns))
	for _, p := range patterns {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		key := strings.ToLower(p)
		if seen[key] {
			continue
		}
		seen[key] = true
		out = append(out, p)
	}
	return out
}

// FormatUAAllowlistFile builds ModSec @pmFromFile content.
func FormatUAAllowlistFile(patterns []string) string {
	patterns = NormalizeUAAllowlist(patterns)
	var b strings.Builder
	b.WriteString("# Generated by NSP — UA allowlist (REQ-RATE-010)\n")
	for _, p := range patterns {
		b.WriteString(p)
		b.WriteByte('\n')
	}
	return b.String()
}

func ValidateWAFPolicy(p models.WAFPolicy) error {
	switch p.EngineMode {
	case "Off", "DetectionOnly", "On":
	default:
		return fmt.Errorf("invalid engine_mode")
	}
	if p.ParanoiaLevel < 1 || p.ParanoiaLevel > 4 {
		return fmt.Errorf("paranoia_level must be 1-4")
	}
	if p.InboundAnomalyScoreThreshold != 0 && (p.InboundAnomalyScoreThreshold < 1 || p.InboundAnomalyScoreThreshold > 10000) {
		return fmt.Errorf("invalid inbound_anomaly_score_threshold")
	}
	if p.OutboundAnomalyScoreThreshold != 0 && (p.OutboundAnomalyScoreThreshold < 1 || p.OutboundAnomalyScoreThreshold > 10000) {
		return fmt.Errorf("invalid outbound_anomaly_score_threshold")
	}
	return nil
}

func ValidateWAFException(e models.WAFException) error {
	if !ruleIDRe.MatchString(e.RuleID) {
		return fmt.Errorf("invalid rule_id")
	}
	if e.Reason == "" {
		return fmt.Errorf("reason required")
	}
	if e.PathPrefix != "" && !pathRe.MatchString(e.PathPrefix) {
		return fmt.Errorf("invalid path_prefix")
	}
	if strings.ContainsAny(e.Argument, "\r\n;\"") {
		return fmt.Errorf("invalid argument")
	}
	return nil
}

// ExceptionIsGlobalDisable is true when rule is removed for all hosts/paths (high impact).
func ExceptionIsGlobalDisable(e models.WAFException) bool {
	return e.HostID == nil && strings.TrimSpace(e.PathPrefix) == "" && strings.TrimSpace(e.Argument) == ""
}

// RenderModSecOverlay builds CRS overlay: paranoia, anomaly, exceptions (REQ-WAF-006/007/008/013).
func RenderModSecOverlay(in WAFRenderInput) (string, error) {
	if err := ValidateWAFPolicy(in.Global); err != nil {
		return "", err
	}
	inbound := in.Global.InboundAnomalyScoreThreshold
	if inbound == 0 {
		inbound = 5
	}
	outbound := in.Global.OutboundAnomalyScoreThreshold
	if outbound == 0 {
		outbound = 4
	}
	var b strings.Builder
	b.WriteString("# Generated by NSP — ModSecurity overlay\n")
	if in.CRSVersion != "" {
		b.WriteString(fmt.Sprintf("# CRS %s\n", escapeNginxString(in.CRSVersion)))
	}
	pl := in.Global.ParanoiaLevel
	b.WriteString(fmt.Sprintf(
		`SecAction "id:10900000,phase:1,nolog,pass,t:none,setvar:tx.blocking_paranoia_level=%d"`+"\n", pl))
	b.WriteString(fmt.Sprintf(
		`SecAction "id:10900001,phase:1,nolog,pass,t:none,setvar:tx.detection_paranoia_level=%d"`+"\n", pl))
	b.WriteString(fmt.Sprintf(
		`SecAction "id:10900002,phase:1,nolog,pass,t:none,setvar:tx.inbound_anomaly_score_threshold=%d"`+"\n", inbound))
	b.WriteString(fmt.Sprintf(
		`SecAction "id:10900003,phase:1,nolog,pass,t:none,setvar:tx.outbound_anomaly_score_threshold=%d"`+"\n", outbound))

	settings := in.ModSecSettings
	if settings.AuditEngine == "" {
		// Legacy fallback from policy flag
		settings = DefaultModSecGlobalSettings()
		if !in.Global.AuditRelevantOnly {
			settings.AuditEngine = "On"
		}
	}
	gs, err := RenderModSecGlobalSettings(settings)
	if err != nil {
		return "", err
	}
	b.WriteString(gs)

	// REQ-RATE-010: allowlisted UA phrases skip the bad-bot deny rule (not full CRS bypass).
	uaFile := "/var/lib/nsp/modsec/ua-allowlist.txt"
	if len(NormalizeUAAllowlist(in.UAAllowlist)) > 0 {
		b.WriteString(fmt.Sprintf(
			`SecRule REQUEST_HEADERS:User-Agent "@pmFromFile %s" \
    "id:1000090,phase:1,pass,nolog,t:none,skipAfter:END_NSP_BAD_BOT"`+"\n", uaFile))
	}
	b.WriteString(`SecRule REQUEST_HEADERS:User-Agent "@pmFromFile /etc/nginx/modsec/bad-bots.txt" \
    "id:1000100,phase:1,deny,status:403,log,msg:'NSP bad bot UA',tag:'nsp/bad-bot'"` + "\n")
	b.WriteString("SecMarker END_NSP_BAD_BOT\n")

	disabled, err := NormalizeDisabledRuleIDs(in.DisabledRules)
	if err != nil {
		return "", err
	}
	disabledSet := DisabledRuleSet(disabled)
	for _, id := range disabled {
		b.WriteString(fmt.Sprintf("SecRuleRemoveById %s\n", id))
	}

	exID := 1001000
	for _, e := range in.Exceptions {
		if !e.Enabled {
			continue
		}
		if err := ValidateWAFException(e); err != nil {
			return "", fmt.Errorf("exception %s: %w", e.ID, err)
		}
		var domain string
		if e.HostID != nil && in.HostDomains != nil {
			domain = in.HostDomains[e.HostID.String()]
		}
		scoped := domain != "" || e.PathPrefix != "" || e.Argument != ""
		if !scoped {
			// Skip duplicate remove if already disabled via catalog toggle
			if disabledSet[e.RuleID] {
				continue
			}
			b.WriteString(fmt.Sprintf("SecRuleRemoveById %s\n", e.RuleID))
			continue
		}
		// Multi-condition exceptions must use SecRule chain (comma-joined SecRule is invalid).
		type cond struct{ target, op string }
		conds := make([]cond, 0, 3)
		if domain != "" {
			conds = append(conds, cond{
				target: "REQUEST_HEADERS:Host",
				op:     fmt.Sprintf(`@rx ^%s(?::\d+)?$`, regexp.QuoteMeta(domain)),
			})
		}
		if e.PathPrefix != "" {
			conds = append(conds, cond{
				target: "REQUEST_URI",
				op:     fmt.Sprintf(`@beginsWith %s`, escapeModSec(e.PathPrefix)),
			})
		}
		if e.Argument != "" {
			conds = append(conds, cond{
				target: fmt.Sprintf("ARGS:%s", escapeModSec(e.Argument)),
				op:     `@rx .`,
			})
		}
		for i, c := range conds {
			last := i == len(conds)-1
			if i == 0 {
				if last {
					b.WriteString(fmt.Sprintf(
						`SecRule %s "%s" \
    "id:%d,phase:1,pass,nolog,ctl:ruleRemoveById=%s"`+"\n",
						c.target, c.op, exID, e.RuleID))
				} else {
					b.WriteString(fmt.Sprintf(
						`SecRule %s "%s" \
    "id:%d,phase:1,pass,nolog,chain"`+"\n",
						c.target, c.op, exID))
				}
				continue
			}
			if last {
				// Chain starter already has pass/nolog; last rule only carries ctl.
				b.WriteString(fmt.Sprintf(
					`SecRule %s "%s" \
    "t:none,ctl:ruleRemoveById=%s"`+"\n",
					c.target, c.op, e.RuleID))
			} else {
				b.WriteString(fmt.Sprintf(
					`SecRule %s "%s" \
    "t:none,chain"`+"\n",
					c.target, c.op))
			}
		}
		exID++
	}

	custom, err := RenderCustomRules(in.CustomRules, in.HostDomains)
	if err != nil {
		return "", err
	}
	b.WriteString(custom)
	return b.String(), nil
}

func escapeModSec(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", "", "\r", "", ";", "")
	return r.Replace(s)
}

// HostEngineDirective returns per-server ModSecurity directives (REQ-WAF-003/004/005).
func HostEngineDirective(enabled bool, global models.WAFPolicy, hostOverride *models.WAFPolicy) string {
	if !enabled {
		return "        modsecurity off;\n"
	}
	mode := global.EngineMode
	polEnabled := global.Enabled
	if hostOverride != nil {
		polEnabled = hostOverride.Enabled
		mode = hostOverride.EngineMode
	}
	if !polEnabled || mode == "Off" {
		return "        modsecurity off;\n"
	}
	file := "/etc/nginx/modsec/engine-DetectionOnly.conf"
	switch mode {
	case "On":
		file = "/etc/nginx/modsec/engine-On.conf"
	case "DetectionOnly":
		file = "/etc/nginx/modsec/engine-DetectionOnly.conf"
	}
	var b strings.Builder
	b.WriteString("        modsecurity on;\n")
	b.WriteString(fmt.Sprintf("        modsecurity_rules_file %s;\n", file))
	return b.String()
}

// ClassifyCRSAttackType maps OWASP CRS rule IDs to attack categories (REQ-WAF-014).
func ClassifyCRSAttackType(ruleID string) string {
	if len(ruleID) < 3 {
		return "other"
	}
	prefix := ruleID
	if len(ruleID) >= 3 {
		prefix = ruleID[:3]
	}
	switch prefix {
	case "920", "921":
		return "protocol"
	case "930":
		return "path_traversal"
	case "931":
		return "rfi"
	case "932":
		return "rce"
	case "933":
		return "php"
	case "934":
		return "generic"
	case "941":
		return "xss"
	case "942":
		return "sqli"
	case "943":
		return "session"
	case "944":
		return "java"
	case "949", "959", "980":
		return "scoring"
	default:
		if strings.HasPrefix(ruleID, "1000") {
			return "custom"
		}
		return "other"
	}
}
