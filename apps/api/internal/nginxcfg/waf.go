var (
	ruleIDRe = regexp.MustCompile(`^[0-9]+$`)
)

// WAFRenderInput feeds ModSecurity overlay + per-host engine directives.
type WAFRenderInput struct {
	Global         models.WAFPolicy
	HostPolicy     map[string]models.WAFPolicy // host id -> policy
	Exceptions     []models.WAFException
	HostDomains    map[string]string // host id -> primary_domain
	CRSVersion     string
	UAAllowlist    []string             // REQ-RATE-010
	ModSecSettings ModSecGlobalSettings // REQ-WAF-017
	CustomRules    CustomRulesBundle    // REQ-WAF-018
	DisabledRules  []string             // global SecRuleRemoveById (REQ-WAF-007 catalog toggles)
}

