package crowdsec

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

// DetectionSettings are allowlisted CrowdSec leaky/scenario knobs (REQ-IDS-017).
// Free-form YAML from the panel is never accepted.
type DetectionSettings struct {
	HTTPProbingCapacity  int    `json:"http_probing_capacity"`  // 404/403/400 distinct paths
	HTTPProbingLeakSpeed string `json:"http_probing_leakspeed"` // e.g. 10s
	HTTPProbingBlackhole string `json:"http_probing_blackhole"` // e.g. 5m
	HTTPCrawlCapacity    int    `json:"http_crawl_capacity"`
	HTTPCrawlLeakSpeed   string `json:"http_crawl_leakspeed"`
	HTTPCrawlBlackhole   string `json:"http_crawl_blackhole"`
	HTTPBFCapacity       int    `json:"http_bf_capacity"`
	HTTPBFLeakSpeed      string `json:"http_bf_leakspeed"`
	HTTPBFBlackhole      string `json:"http_bf_blackhole"`
	BanDuration          string `json:"ban_duration"` // profiles.yaml decision duration
}

var durationRe = regexp.MustCompile(`^[0-9]+(\.[0-9]+)?(s|m|h)$`)

func DefaultDetectionSettings() DetectionSettings {
	return DetectionSettings{
		HTTPProbingCapacity: 10, HTTPProbingLeakSpeed: "10s", HTTPProbingBlackhole: "5m",
		HTTPCrawlCapacity: 40, HTTPCrawlLeakSpeed: "0.5s", HTTPCrawlBlackhole: "1m",
		HTTPBFCapacity: 5, HTTPBFLeakSpeed: "10s", HTTPBFBlackhole: "1m",
		BanDuration: "4h",
	}
}

func (s *DetectionSettings) Normalize() {
	d := DefaultDetectionSettings()
	if s.HTTPProbingCapacity == 0 {
		s.HTTPProbingCapacity = d.HTTPProbingCapacity
	}
	if s.HTTPProbingLeakSpeed == "" {
		s.HTTPProbingLeakSpeed = d.HTTPProbingLeakSpeed
	}
	if s.HTTPProbingBlackhole == "" {
		s.HTTPProbingBlackhole = d.HTTPProbingBlackhole
	}
	if s.HTTPCrawlCapacity == 0 {
		s.HTTPCrawlCapacity = d.HTTPCrawlCapacity
	}
	if s.HTTPCrawlLeakSpeed == "" {
		s.HTTPCrawlLeakSpeed = d.HTTPCrawlLeakSpeed
	}
	if s.HTTPCrawlBlackhole == "" {
		s.HTTPCrawlBlackhole = d.HTTPCrawlBlackhole
	}
	if s.HTTPBFCapacity == 0 {
		s.HTTPBFCapacity = d.HTTPBFCapacity
	}
	if s.HTTPBFLeakSpeed == "" {
		s.HTTPBFLeakSpeed = d.HTTPBFLeakSpeed
	}
	if s.HTTPBFBlackhole == "" {
		s.HTTPBFBlackhole = d.HTTPBFBlackhole
	}
	if s.BanDuration == "" {
		s.BanDuration = d.BanDuration
	}
}

func (s DetectionSettings) Validate() error {
	s.Normalize()
	for _, c := range []int{s.HTTPProbingCapacity, s.HTTPCrawlCapacity, s.HTTPBFCapacity} {
		if c < 1 || c > 10000 {
			return fmt.Errorf("capacity must be 1..10000")
		}
	}
	for _, d := range []string{
		s.HTTPProbingLeakSpeed, s.HTTPProbingBlackhole,
		s.HTTPCrawlLeakSpeed, s.HTTPCrawlBlackhole,
		s.HTTPBFLeakSpeed, s.HTTPBFBlackhole, s.BanDuration,
	} {
		if !durationRe.MatchString(strings.TrimSpace(d)) {
			return fmt.Errorf("invalid duration %q (use Ns/Nm/Nh, e.g. 10s, 0.5s, 4h)", d)
		}
	}
	return nil
}

// RenderOverrideFiles returns allowlisted basename → YAML content.
func (s DetectionSettings) RenderOverrideFiles() (map[string]string, error) {
	if err := s.Validate(); err != nil {
		return nil, err
	}
	s.Normalize()
	return map[string]string{
		"http-probing.yaml":           renderHTTPProbing(s),
		"http-crawl-non_statics.yaml": renderHTTPCrawl(s),
		"http-generic-bf.yaml":        renderHTTPBF(s),
		"profiles.yaml":               renderProfiles(s),
	}, nil
}

func renderHTTPProbing(s DetectionSettings) string {
	return `# Generated by NSP — do not edit by hand (REQ-IDS-017)
type: leaky
name: crowdsecurity/http-probing
description: "Detect site scanning/probing from a single ip"
filter: "evt.Meta.service == 'http' && evt.Meta.http_status in ['404', '403', '400'] && evt.Parsed.static_ressource == 'false'"
groupby: "evt.Meta.source_ip + '/' + evt.Parsed.target_fqdn"
distinct: "evt.Meta.http_path"
capacity: ` + strconv.Itoa(s.HTTPProbingCapacity) + `
reprocess: true
leakspeed: "` + s.HTTPProbingLeakSpeed + `"
blackhole: ` + s.HTTPProbingBlackhole + `
labels:
  remediation: true
  classification:
    - attack.T1595
  behavior: "http:scan"
  label: "HTTP Probing"
  spoofable: 0
  service: http
  confidence: 1
`
}

